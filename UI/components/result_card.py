"""Reusable card for displaying a single compound result."""

from collections.abc import Mapping
from typing import Any

import streamlit as st

import config
from UI.utils.helpers import (
    AFFINITY_HELP,
    AFFINITY_LABEL,
    NOT_AVAILABLE_YET,
    PRIORITY_HELP,
    PRIORITY_LABEL,
    format_affinity,
    format_descriptor,
    format_priority,
)


def _render_docking(docking: Mapping[str, Any] | None) -> None:
    """Show the docking outcome: a real affinity, a failure, or nothing yet."""
    if docking is None:
        st.caption(f"**{AFFINITY_LABEL}:** {NOT_AVAILABLE_YET}", help=AFFINITY_HELP)
    elif docking["docking_success"]:
        st.markdown(f"{AFFINITY_LABEL}: **{format_affinity(docking['best_affinity_kcal_mol'])}**", help=AFFINITY_HELP)
        st.caption(f"{docking['poses_generated']} poses generated by AutoDock Vina")
    else:
        st.markdown("✕ **Docking: Failed**")
        with st.expander("Why did docking fail?"):
            st.write(docking["error"])


def _render_priority(ranking: Mapping[str, Any] | None) -> None:
    """Show the Screening Priority Score, or why the compound is not ranked."""
    if ranking is None:
        st.caption(f"**{PRIORITY_LABEL}:** {NOT_AVAILABLE_YET}", help=PRIORITY_HELP)
    elif ranking["rank"] is None:
        st.caption(f"**{PRIORITY_LABEL}:** {ranking['ranking_status']}", help=PRIORITY_HELP)
    else:
        st.markdown(f"{PRIORITY_LABEL}: **{format_priority(ranking['screening_priority_score'])}**", help=PRIORITY_HELP)


def render_top_card(entry: Mapping[str, Any]) -> None:
    """Compact card for a top-ranked compound: rank, name, score, affinity, one line of why.

    Args:
        entry: A ranked entry from ``backend.ranking`` (values shown as given).
    """
    with st.container(border=True):
        st.markdown(f"**#{entry['rank']} · {entry['name']}**")
        st.markdown(f"{PRIORITY_LABEL}: **{format_priority(entry['screening_priority_score'])}**", help=PRIORITY_HELP)
        st.markdown(f"{AFFINITY_LABEL}: **{format_affinity(entry['docking_affinity'])}**", help=AFFINITY_HELP)
        st.caption(entry["explanation"])


def render_result_card(
    compound_name: str | None = None,
    properties: Mapping[str, float | int | None] | None = None,
    smiles: str | None = None,
    error: str | None = None,
    docking: Mapping[str, Any] | None = None,
    ranking: Mapping[str, Any] | None = None,
) -> None:
    """Display one compound result as a bordered card.

    Only real values are shown. Anything missing is labelled "Not available
    yet" (scores) or "—" (descriptors) instead of a placeholder number.

    Args:
        compound_name: Name or identifier of the compound.
        properties: RDKit descriptors keyed as in ``config.DESCRIPTORS``.
        smiles: The compound's SMILES string.
        error: Why descriptor calculation failed, if it did.
        docking: The compound's docking result from ``backend.docking``.
        ranking: The compound's entry from ``backend.ranking``.
    """
    with st.container(border=True):
        rank = ranking.get("rank") if ranking else None
        rank_label = f"#{rank} · " if rank is not None else ""
        st.markdown(f"**{rank_label}{compound_name or 'Unnamed compound'}**")
        if smiles:
            st.caption(f"SMILES: `{smiles}`")

        if error:
            st.error(f"Descriptor calculation failed: {error}", icon=":material/error:")
        elif properties:
            columns = st.columns(2)
            for index, (key, descriptor) in enumerate(config.DESCRIPTORS.items()):
                columns[index % 2].markdown(
                    f"{descriptor['label']}: **{format_descriptor(key, properties.get(key))}**", help=descriptor["help"]
                )
        else:
            st.caption(f"**Molecular properties:** {NOT_AVAILABLE_YET}")

        _render_docking(docking)
        _render_priority(ranking)

        if ranking and ranking["rank"] is not None:
            st.caption(ranking["explanation"])
        st.caption("Computational prediction only. Requires laboratory validation.")
